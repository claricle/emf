//! Standalone unchanged-byte parity for the manifest's 208 valid EMF fixtures.
//!
//! The saved Ruby observations are provenance, not a runtime dependency or typed
//! model oracle. All 231 files have inventory/integrity checks; the corrupted
//! and WMF cohorts do not enter valid EMF acceptance. Typed decoding/edit parity
//! and malformed-input compatibility remain covered by their dedicated targets.

#[path = "support/sha256.rs"]
mod sha256;

use emf_core::{detect_format, parse, serialize, Format, ParseLimits};
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

const INDEX: &str = include_str!("support/fixture_manifest.tsv");
const MANIFEST: &[u8] = include_bytes!("../../../../spec/fixtures/manifest.json");
const EXPECTED_COUNTS: [(&str, usize); 5] = [
    ("emf", 186),
    ("emf-corrupted", 21),
    ("emf-ea", 21),
    ("simple", 1),
    ("wmf", 2),
];

struct Fixture<'a> {
    path: &'a str,
    size: usize,
    sha256: &'a str,
}

impl Fixture<'_> {
    fn cohort(&self) -> &str {
        self.path.split('/').nth(2).unwrap()
    }

    fn valid_emf(&self) -> bool {
        matches!(self.cohort(), "emf" | "emf-ea" | "simple")
    }
}

fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn inventory() -> Vec<Fixture<'static>> {
    let mut lines = INDEX.lines();
    assert_eq!(
        lines.next(),
        Some("# Generated by generate_fixture_index.py; do not edit.")
    );
    let expected_hash = lines
        .next()
        .unwrap()
        .strip_prefix("# manifest-sha256\t")
        .unwrap();
    assert_eq!(
        sha256::digest(MANIFEST),
        expected_hash,
        "stale fixture index: run python3 emf-rs/crates/emf-core/tests/support/generate_fixture_index.py"
    );
    let mut paths = BTreeSet::new();
    let mut counts = BTreeMap::new();
    let fixtures: Vec<_> = lines
        .map(|line| {
            let fields: Vec<_> = line.split('\t').collect();
            assert_eq!(fields.len(), 3, "invalid index row: {line}");
            let path = fields[0];
            let components: Vec<_> = path.split('/').collect();
            assert!(components.len() >= 4 && components[..2] == ["spec", "fixtures"]);
            assert!(components
                .iter()
                .all(|part| !matches!(*part, "" | "." | "..")));
            assert!(paths.insert(path), "duplicate fixture: {path}");
            let fixture = Fixture {
                path,
                size: fields[1].parse().expect("fixture byte count"),
                sha256: fields[2],
            };
            assert_eq!(fixture.sha256.len(), 64, "SHA256 length: {path}");
            assert!(fixture
                .sha256
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)));
            let extension = if fixture.cohort() == "wmf" {
                "wmf"
            } else {
                "emf"
            };
            assert_eq!(Path::new(path).extension().unwrap(), extension);
            *counts.entry(fixture.cohort().to_owned()).or_insert(0) += 1;
            fixture
        })
        .collect();
    let expected: BTreeMap<_, _> = EXPECTED_COUNTS
        .into_iter()
        .map(|(name, count)| (name.to_owned(), count))
        .collect();
    assert_eq!(counts, expected, "fixture cohort counts");
    fixtures
}

fn fixture_paths(root: &Path, directory: &Path, paths: &mut BTreeSet<String>) {
    for entry in std::fs::read_dir(directory).expect("fixture directory") {
        let entry = entry.unwrap();
        let kind = entry.file_type().unwrap();
        assert!(
            !kind.is_symlink(),
            "symlink in fixture inventory: {:?}",
            entry.path()
        );
        let path = entry.path();
        if kind.is_dir() {
            fixture_paths(root, &path, paths);
        } else if matches!(
            path.extension().and_then(|value| value.to_str()),
            Some("emf" | "wmf")
        ) {
            let relative = path.strip_prefix(root).unwrap();
            // Manifest paths always use forward slashes, including on Windows.
            paths.insert(
                relative
                    .components()
                    .map(|part| part.as_os_str().to_str().unwrap())
                    .collect::<Vec<_>>()
                    .join("/"),
            );
        }
    }
}

fn checked_bytes(root: &Path, fixture: &Fixture<'_>) -> Vec<u8> {
    let bytes = std::fs::read(root.join(fixture.path))
        .unwrap_or_else(|error| panic!("{}: {error}", fixture.path));
    assert_eq!(bytes.len(), fixture.size, "byte count: {}", fixture.path);
    assert_eq!(
        sha256::digest(&bytes),
        fixture.sha256,
        "SHA256: {}",
        fixture.path
    );
    bytes
}

#[test]
fn manifest_covers_all_231_fixture_paths_and_bytes() {
    let root = repository();
    let fixtures = inventory();
    let mut actual = BTreeSet::new();
    fixture_paths(&root, &root.join("spec/fixtures"), &mut actual);
    let indexed: BTreeSet<_> = fixtures
        .iter()
        .map(|fixture| fixture.path.to_owned())
        .collect();
    assert_eq!(actual, indexed, "missing or unlisted fixture paths");
    for fixture in &fixtures {
        checked_bytes(&root, fixture);
    }
}

#[test]
fn all_208_valid_emf_fixtures_serialize_byte_identically() {
    let root = repository();
    let fixtures = inventory();
    let mut count = 0;
    // Sequential traversal bounds live memory to one fixture/document/output.
    for fixture in fixtures.iter().filter(|fixture| fixture.valid_emf()) {
        let bytes = checked_bytes(&root, fixture);
        assert_eq!(detect_format(&bytes), Ok(Format::Emf), "{}", fixture.path);
        let document = parse(&bytes, &ParseLimits::default())
            .unwrap_or_else(|error| panic!("{}: parse failed: {error:?}", fixture.path));
        let output = serialize(&document)
            .unwrap_or_else(|error| panic!("{}: serialize failed: {error:?}", fixture.path));
        // Avoid printing megabytes of fixture content on a mismatch.
        assert!(
            output == bytes,
            "unchanged bytes differ: {} (first mismatch {:?}; lengths {} -> {})",
            fixture.path,
            bytes
                .iter()
                .zip(&output)
                .position(|(before, after)| before != after),
            bytes.len(),
            output.len()
        );
        count += 1;
    }
    assert_eq!(
        count, 208,
        "valid EMF acceptance must cover every valid cohort"
    );
}
