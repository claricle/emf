#!/usr/bin/env python3
"""Generate the standalone Rust inventory; no Ruby parser is invoked.

Run from any directory, with --check to verify the committed index. Fixture bytes
are checked by fixture_parity.rs, so regeneration does not read the binary corpus.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path, PurePosixPath
import re

ROOT = Path(__file__).resolve().parents[5]
MANIFEST = ROOT / "spec/fixtures/manifest.json"
INDEX = Path(__file__).with_name("fixture_manifest.tsv")
COUNTS = {"emf": 186, "emf-ea": 21, "simple": 1, "emf-corrupted": 21, "wmf": 2}


def render(raw):
    manifest = json.loads(raw)
    if manifest["schema_version"] != 2:
        raise ValueError("unsupported fixture manifest schema")
    entries = manifest["fixtures"]
    paths = [entry["path"] for entry in entries]
    if len(set(paths)) != len(paths):
        raise ValueError("duplicate fixture path")
    counts = Counter()
    rows = []
    for entry in sorted(entries, key=lambda entry: entry["path"]):
        path = entry["path"]
        parts = PurePosixPath(path).parts
        if (len(parts) < 4 or parts[:2] != ("spec", "fixtures")
                or ".." in parts or str(PurePosixPath(path)) != path
                or any(char in path for char in '\t\r\n')):
            raise ValueError("invalid fixture path: " + path)
        cohort = parts[2]
        counts[cohort] += 1
        expected = "wmf" if cohort == "wmf" else "emf"
        if PurePosixPath(path).suffix != "." + expected or entry["expected_format"] != expected:
            raise ValueError("invalid fixture format: " + path)
        if not re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]):
            raise ValueError("invalid SHA256: " + path)
        if type(entry["size_bytes"]) is not int or entry["size_bytes"] < 0:
            raise ValueError("invalid fixture size: " + path)
        # Directory provenance defines the valid cohort, not Ruby's ability to
        # parse damaged files. Even the nine 'parsed' corrupted files stay out.
        if cohort in ("emf", "emf-ea", "simple") and (
                entry.get("outcome") != "parsed" or entry.get("detected_format") != "emf"
                or "backend_exception" in entry or "safety_failure" in entry):
            raise ValueError("valid EMF cohort has a non-parsed observation: " + path)
        rows.append(f'{path}\t{entry["size_bytes"]}\t{entry["sha256"]}\n')
    if counts != COUNTS or manifest["counts"] != COUNTS:
        raise ValueError("fixture cohort counts differ from the accepted inventory")
    return ("# Generated by generate_fixture_index.py; do not edit.\n"
            + "# manifest-sha256\t" + hashlib.sha256(raw).hexdigest() + "\n"
            + "".join(rows))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(MANIFEST.read_bytes())
    if args.check:
        if INDEX.read_text() != generated:
            parser.error("stale index; run " + str(Path(__file__)))
        print("Standalone Rust fixture index matches the manifest (231 entries).")
    else:
        INDEX.write_text(generated)


if __name__ == "__main__":
    main()
